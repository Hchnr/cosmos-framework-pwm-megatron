#!/usr/bin/env python3
"""Build the standalone WorldArena viewer (stdlib only; no inference is run).

First migration:
    python tools/build_worldarena_viewer.py --import-html outputs/worldarena_eval25_480p_steps50/index.html
Rebuild after editing tools/worldarena_viewer/ or <root>/viewer_data.json:
    python tools/build_worldarena_viewer.py
The result and transfer index.html files are both regenerated by default.
"""

import argparse
import html
import json
import re
from pathlib import Path

ASSETS = Path(__file__).with_name("worldarena_viewer")
DEFAULT_ROOT = Path("outputs/worldarena_eval25_480p_steps50")


def import_legacy(source: str) -> dict:
    """Migrate only the displayed runs; never discover obsolete runs from disk."""
    embedded = re.search(r'<script id="viewerData" type="application/json">(.*?)</script>', source, re.S)
    if embedded:
        return json.loads(embedded[1])
    samples = []
    for match in re.finditer(
        r"\{name: '([^']+)', modelMode: '([^']+)', numFrames: (\d+), fps: (\d+), seed: (\d+)\}", source
    ):
        name, mode, frames, fps, seed = match.groups()
        samples.append(dict(name=name, modelMode=mode, numFrames=int(frames), fps=int(fps), seed=int(seed)))
    prompts = {}
    for name in ("prompts", "upsampledPrompts"):
        match = re.search(rf"const {name} = (\{{.*?\n\s*\}});", source, re.S)
        if not match:
            raise ValueError(f"Cannot find legacy {name}")
        if name == "prompts":
            # The old page used plain template literals, not JSON, for original prompts.
            pairs = re.findall(r"'([^']+)': `([^`\\]*)`,?", match[1])
            prompts[name] = dict(pairs)
            if len(pairs) != len(samples) or any("${" in value for _, value in pairs):
                raise ValueError("Unsupported legacy prompt escaping; migrate these prompts explicitly")
        else:
            prompts[name] = json.loads(match[1])
    titles = {
        ident: html.unescape(title) for title, ident in re.findall(r'<h2>(.*?)</h2>\s*<video id="([^"]+)"', source)
    }
    runs = []
    for ident, directory in re.findall(r"updateVideo\((\w+), `([^/`]+)/\$\{name\}/vision.mp4`\)", source):
        title = titles[ident]
        step_match = re.search(r"iter(\d+)", directory)
        step = int(step_match[1]) if step_match else None
        family = "baseline" if step is None else "v1" if "VLM v1" in title else "v2" if "VLM v2" in title else "native"
        tags = []
        if "USR v2" in title:
            tags.append(["USR v2 · R7-1056", "usr"])
        if "fp8_w8a8" in directory:
            tags.extend([["FP8 W8A8", "fp8"], ["per-row", "neutral"], ["DP8", "neutral"]])
        if "fsdp4_dp2" in directory:
            tags.append(["FSDP4 × DP2", "neutral"])
        if "compile_language" in directory:
            tags.append(["language compile", "compile"])
        if "batched4" in directory:
            tags.append(["batch 4", "neutral"])
        elif "unbatched" in directory:
            tags.append(["unbatched", "neutral"])
        runs.append(
            dict(
                id=ident,
                directory=directory,
                title=title,
                step=step,
                family=family,
                prompt="reasoner" if "reasoner_upsampled" in directory else "original",
                tags=tags,
            )
        )
    if not samples or not runs or set(titles) != {run["id"] for run in runs}:
        raise ValueError("Incomplete legacy viewer; refusing to drop samples or runs")
    return dict(samples=samples, runs=runs, **prompts)


def prepare(data: dict) -> dict:
    runs = data["runs"]
    if not runs or len({r["id"] for r in runs}) != len(runs):
        raise ValueError("Run IDs must be nonempty and unique")
    if len({r["directory"] for r in runs}) != len(runs):
        raise ValueError("Run directories must be unique")
    families = {"baseline": 0, "native": 1, "v1": 2, "v2": 3}
    for run in runs:
        if run["family"] not in families or run["prompt"] not in {"original", "reasoner"}:
            raise ValueError(f"Unknown family or prompt: {run['id']}")
        if not re.fullmatch(r"[\w-]+", run["directory"]):
            raise ValueError(f"Expected a single relative run directory: {run['directory']}")
        if (run["step"] is None) != (run["family"] == "baseline"):
            raise ValueError(f"Only baseline may omit training step: {run['id']}")
        if run["step"] is not None and (not isinstance(run["step"], int) or run["step"] < 0):
            raise ValueError(f"Invalid training step: {run['id']}")
    runs.sort(
        key=lambda r: (
            r["step"] is not None,
            r["step"] or 0,
            families[r["family"]],
            r["prompt"] == "reasoner",
            "fp8" in r["directory"],
            "unbatched" in r["directory"],
            r["id"],
        )
    )
    names = [s["name"] for s in data["samples"]]
    if not names or len(set(names)) != len(names):
        raise ValueError("Samples must be nonempty and unique")
    for name in names:
        if not re.fullmatch(r"[\w-]+", name) or name not in data["prompts"] or name not in data["upsampledPrompts"]:
            raise ValueError(f"Invalid sample or missing prompt: {name}")
    return data


def render(data: dict) -> str:
    # Escaping '<' prevents prompt text from terminating an inline script element.
    payload = json.dumps(data, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    page = (ASSETS / "index.html").read_text()
    for key, value in (
        ("STYLE", (ASSETS / "viewer.css").read_text()),
        ("SCRIPT", (ASSETS / "viewer.js").read_text()),
        ("DATA", payload),
    ):
        page = page.replace(f"<!-- {key} -->", value)
    return page


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--data", type=Path, help="Default: <root>/viewer_data.json")
    parser.add_argument("--import-html", type=Path, help="Migrate a legacy page into the data file once")
    parser.add_argument("--output", type=Path, nargs="+", help="HTML destinations; default: root and sibling transfer")
    args = parser.parse_args()
    data_path = args.data or args.root / "viewer_data.json"
    data = prepare(
        import_legacy(args.import_html.read_text()) if args.import_html else json.loads(data_path.read_text())
    )
    page = render(data)
    destinations = args.output or [
        args.root / "index.html",
        args.root.with_name(args.root.name + "_transfer") / "index.html",
    ]
    data_path.parent.mkdir(parents=True, exist_ok=True)
    data_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    for destination in destinations:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(page)
        print(f"Built {destination}: {len(data['runs'])} checkpoints, {len(data['samples'])} samples")


if __name__ == "__main__":
    main()
