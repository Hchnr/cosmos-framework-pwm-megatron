"""Run matched TP4-sharded-VAE and FSDP4 raw benchmarks under an owned lock.

The parent must be the standard GPU qualification queue, which already waits
for its declared predecessors, takes the shared lock and checks GPU idleness.
Both runs use the same raw fixtures, configuration and model/optimizer source;
the native source and converted TP state are compared exactly before timing.
SHA-256 checks of weight files, fixtures and sources occur only outside the
measured updates. PID namespace limitations make restricted monitoring
provisional. This is performance evidence, not numerical acceptance.
"""

import argparse
import fcntl
import json
import os
import subprocess
import time
from pathlib import Path

import psutil

from tools import run_tp4_fsdp4_raw_clean_coordinator as prior
from tools import tp_pp_gpu_process_monitor as gpu_monitor
from tools.compare_tp4_fsdp4_microbatch_benchmark import compare
from tools.run_tp4_sharded_vae_raw_benchmark import _digest, validate_qualification
from tools.tp_pp_fair_runtime import validate_reports

ROOT = Path(__file__).resolve().parents[1]
LOCK = Path("/tmp/cosmos-tp-pp-norm-post-fused.lock")


def parent_owns_queue_lock():
    parent = psutil.Process(os.getppid())
    if "queue_tp_pp_sharded_vae_gpu.py" not in " ".join(parent.cmdline()):
        raise RuntimeError("Launch through the standard GPU qualification queue")
    identity = LOCK.stat()
    found = False
    for fd in (Path("/proc") / str(parent.pid) / "fd").iterdir():
        try:
            info = fd.stat()
        except FileNotFoundError:
            continue
        if (info.st_dev, info.st_ino) == (identity.st_dev, identity.st_ino):
            found = True
            break
    if not found:
        raise RuntimeError("The queue parent does not hold the shared lock file open")
    with LOCK.open("a+") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            return
        fcntl.flock(handle, fcntl.LOCK_UN)
    raise RuntimeError("The shared GPU lock is not held")


def fingerprint_path(path):
    path = Path(path).resolve(strict=True)
    if path.is_file():
        return {"kind": "file", "files": {path.name: {"size": path.stat().st_size, "sha256": _digest(path)}}}
    if not path.is_dir():
        raise ValueError(f"Unsupported fingerprint input: {path}")
    files = {}
    for item in sorted(path.rglob("*")):
        if item.is_symlink():
            raise ValueError(f"Refusing symlink in weight fingerprint: {item}")
        if item.is_file():
            files[str(item.relative_to(path))] = {"size": item.stat().st_size, "sha256": _digest(item)}
    if not files:
        raise ValueError(f"Empty weight fingerprint: {path}")
    return {"kind": "tree", "files": files}


def source_contract(tp4, tp2, source):
    manifests = [json.loads((path / "manifest.json").read_text()) for path in (tp4, tp2)]
    for path, manifest, topology in zip((tp4, tp2), manifests, ((4, 1), (2, 2)), strict=True):
        if (
            manifest.get("format") != "cosmos_tp_pp_canonical"
            or manifest.get("format_version") != 1
            or manifest.get("complete") is not True
            or not manifest.get("parameters")
            or (manifest.get("tp"), manifest.get("pp")) != topology
            or Path(manifest.get("source", "")).resolve() != source.resolve()
            or not (path / ".save_complete").is_file()
        ):
            raise ValueError(f"Incompatible canonical checkpoint: {path}")
    return {"source": str(source.resolve()), "tp4_parameters": len(manifests[0]["parameters"])}


def source_paths(tp4, tp2, source, fixture, vae, hf):
    paths = {"tp4_bundle": tp4, "native_checkpoint": source, "tp2_logical_state": tp2 / "logical_state"}
    paths.update(tp2_manifest=tp2 / "manifest.json", tp2_complete=tp2 / ".save_complete")
    paths.update(raw_fixture=fixture, vae_checkpoint=vae, hf_checkpoint=hf)
    return paths


def fingerprints(paths):
    return {name: fingerprint_path(path) for name, path in paths.items()}


def fingerprint_code(sequence_helper, collective_candidate):
    """Pin executable inputs without including runtime-generated bytecode."""
    paths = [
        item
        for directory in (ROOT / "cosmos_framework", ROOT / "tools")
        for item in directory.rglob("*.py")
        if item.is_file()
    ]
    paths.extend((Path(sequence_helper), Path(collective_candidate)))
    result = {}
    for path in sorted(set(paths)):
        if path.is_symlink():
            raise ValueError(f"Refusing symlink in executable fingerprint: {path}")
        result[str(path.resolve())] = _digest(path)
    return result


def verify_logical_state(tp2, source):
    count = 0
    for component in ("trainer", "scheduler", "dataloader"):
        base = source / component
        target = tp2 / "logical_state" / component
        originals = {path.relative_to(base) for path in base.rglob("*") if path.is_file()}
        copies = {path.relative_to(target) for path in target.rglob("*") if path.is_file()}
        if not originals or originals != copies:
            raise ValueError(f"Native logical state file coverage differs: {component}")
        for relative in sorted(originals):
            old, copy = base / relative, target / relative
            if not copy.is_file() or _digest(old) != _digest(copy):
                raise ValueError(f"Native logical state differs: {old}")
            count += 1
    if count == 0:
        raise ValueError("No logical state files were compared")
    return count


def memory_events():
    path = Path("/sys/fs/cgroup/memory.events")
    if not path.exists():
        return None
    return {key: int(value) for key, value in (line.split() for line in path.read_text().splitlines())}


def peak_memory(root, backend):
    log_root = root / "training"
    if backend == "tp":
        log_root /= "cosmos3_action/action128/tp4_microbatch"
    result = {}
    for rank in range(4):
        rows = [json.loads(line) for line in (log_root / f"updates.rank{rank}.jsonl").read_text().splitlines()]
        if len(rows) != 7 or any("peak_cuda_allocated_bytes" not in row for row in rows):
            raise ValueError(f"Missing full-update CUDA memory records: {backend} rank {rank}")
        result[str(rank)] = {
            "all_updates_peak_allocated_bytes": max(row["peak_cuda_allocated_bytes"] for row in rows),
            "measured_updates_peak_allocated_bytes": max(row["peak_cuda_allocated_bytes"] for row in rows[2:]),
        }
    return result


class SequenceAdapter:
    def __init__(self, sequence, work, qualification, report, backend):
        self.TP2, self.TP4, self.TOML, self.SPOOL = sequence.TP2, sequence.TP4, sequence.TOML, sequence.SPOOL
        self.WORK, self.ENV, self.python = work, dict(sequence.ENV), sequence.PYTHON
        self.qualification, self.report, self.backend = qualification, report, backend
        self.ENV["PYTHONPATH"] = str(work)

    def distributed(self, entry, *arguments):
        command = [self.python, "-m", "torch.distributed.run", "--standalone", "--nproc-per-node=4"]
        if self.backend == "tp":
            command += [
                str(self.WORK / "tools/run_tp4_sharded_vae_raw_benchmark.py"),
                "--vae-qualification-dir",
                str(self.qualification),
                "--bridge-report-dir",
                str(self.report),
            ]
        else:
            command += [str(self.WORK / entry)]
        return [*command, *(str(value) for value in arguments)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sequence-helper", type=Path, required=True)
    parser.add_argument("--vae-qualification-dir", type=Path, required=True)
    parser.add_argument("--raw-fixture", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--poll-seconds", type=float, default=2)
    parser.add_argument("--timeout-seconds", type=float, default=21600)
    parser.add_argument("--pid-monitor-mode", choices=("strict", "restricted"), default="strict")
    parser.add_argument("--host-proc", type=Path)
    args = parser.parse_args()
    if not 0 < args.poll_seconds <= 60 or args.timeout_seconds <= 0:
        parser.error("Invalid poll or timeout")
    parent_owns_queue_lock()
    args.output.mkdir(parents=True, exist_ok=False)
    status = args.output / "coordinator_result.json"
    result = {
        "completed": False,
        "failure": None,
        "runs": {},
        "scope": __doc__,
        "pid_monitor_mode": args.pid_monitor_mode,
        "provisional": args.pid_monitor_mode == "restricted",
        "performance_acceptance": False,
    }
    prior.save(status, result)
    try:
        sequence = prior.load_module(args.sequence_helper, "_sharded_raw_sequence")
        environment = dict(sequence.ENV)
        expected = validate_qualification(
            args.vae_qualification_dir, args.raw_fixture, ROOT, sequence.TOML, environment
        )
        source = Path(environment["BASE_CHECKPOINT_PATH"])
        tp4, tp2 = Path(sequence.TP4), Path(sequence.TP2)
        result["source_contract"] = source_contract(tp4, tp2, source)
        paths = source_paths(
            tp4,
            tp2,
            source,
            args.raw_fixture,
            Path(environment["WAN_VAE_PATH"]),
            Path(environment["HF_MODEL_PATH"]),
        )
        result["fixture_file_sha256"] = expected
        result["weights_before"] = fingerprints(paths)
        result["code_before"] = fingerprint_code(
            args.sequence_helper, environment["COSMOS_TP_PP_COLLECTIVES_CANDIDATE"]
        )
        result["logical_state_files_equal"] = verify_logical_state(tp2, source)
        prior.save(status, result)
        verify_env = dict(environment, CUDA_VISIBLE_DEVICES="", LD_LIBRARY_PATH="", PYTHONPATH=str(ROOT))
        with (args.output / "tp4_canonical_verification.log").open("x") as log:
            command = [
                sequence.PYTHON,
                str(ROOT / "tools/verify_cosmos_tp_pp_conversion.py"),
                str(tp4),
                "--output",
                str(args.output / "tp4_canonical_verification.json"),
            ]
            subprocess.run(command, cwd=ROOT, env=verify_env, stdout=log, stderr=subprocess.STDOUT, check=True)
        verification = json.loads((args.output / "tp4_canonical_verification.json").read_text())
        if not verification.get("passed") or not verification.get("full_conversion"):
            raise ValueError("TP4 conversion does not exactly match the native checkpoint")
        if set(verification["checked_parameters"]) != set(
            json.loads((tp4 / "manifest.json").read_text())["parameters"]
        ):
            raise ValueError("TP4 conversion verification did not cover every canonical parameter")
        if fingerprints(paths) != result["weights_before"]:
            raise RuntimeError("Weights changed during canonical verification")
        host_proc = gpu_monitor.validate_host_proc(args.host_proc) if args.pid_monitor_mode == "strict" else None
        inventory = prior.query_gpu_inventory()
        devices = gpu_monitor.query_device_nodes(inventory) if args.pid_monitor_mode == "restricted" else None
        result["gpu_inventory"] = inventory
        deadline = time.monotonic() + args.timeout_seconds
        initial_memory_events = memory_events()
        result["cgroup_memory_events_before"] = initial_memory_events

        def check_run():
            if time.monotonic() >= deadline:
                raise TimeoutError("Benchmark exceeded its deadline")
            events = memory_events()
            if (
                initial_memory_events
                and events
                and any(events.get(key, 0) > initial_memory_events.get(key, 0) for key in ("oom", "oom_kill"))
            ):
                raise RuntimeError("Cgroup OOM counter increased")

        for backend in ("tp", "fsdp"):
            if prior.query_gpu_users(inventory):
                raise RuntimeError(f"GPU was occupied before {backend} benchmark")
            monitor = (
                gpu_monitor.StrictMonitor(inventory, host_proc)
                if args.pid_monitor_mode == "strict"
                else gpu_monitor.RestrictedMonitor(inventory, devices)
            )
            adapter = SequenceAdapter(sequence, ROOT, args.vae_qualification_dir, args.output / "bridge", backend)
            prior.run_benchmark(
                adapter,
                backend,
                args.output,
                args.raw_fixture,
                inventory,
                result,
                status,
                args.poll_seconds,
                check_run,
                monitor,
            )
            while prior.query_gpu_users(inventory):
                check_run()
                time.sleep(args.poll_seconds)
            result[f"weights_after_{backend}"] = fingerprints(paths)
            if result[f"weights_after_{backend}"] != result["weights_before"]:
                raise RuntimeError(f"Weight or fixture content changed during {backend} benchmark")
            if (
                fingerprint_code(args.sequence_helper, environment["COSMOS_TP_PP_COLLECTIVES_CANDIDATE"])
                != result["code_before"]
            ):
                raise RuntimeError(f"Executable source changed during {backend} benchmark")
            if backend == "tp":
                for rank in range(4):
                    report = json.loads((args.output / "bridge" / f"sharded_vae_bridge.rank{rank}.json").read_text())
                    if not report.get("passed") or report.get("slots") != 21 or report.get("vae_calls") != 21:
                        raise RuntimeError(f"TP sharded VAE bridge failed for rank {rank}")
            prior.save(status, result)
        result["runtime_fairness"] = validate_reports(args.output)
        result["comparison"] = compare(args.output / "tp", args.output / "fsdp")
        result["comparison"]["runtime_fairness"] = result["runtime_fairness"]
        for backend in ("tp", "fsdp"):
            window = result["runtime_fairness"]["windows"][backend]
            comparison = result["comparison"][backend]
            measured_samples = comparison["global_samples_per_update"] * comparison["contract"]["measured_updates"]
            comparison["window_seconds"] = window["seconds"]
            comparison["window_samples"] = measured_samples
            comparison["window_global_samples_per_second"] = measured_samples / window["seconds"]
        result["comparison"]["window_tp_over_fsdp_sample_throughput"] = (
            result["comparison"]["tp"]["window_global_samples_per_second"]
            / result["comparison"]["fsdp"]["window_global_samples_per_second"]
        )
        result["comparison"]["primary_metric"] = (
            "five measured updates between the first raw-prepare boundary and the final optimizer boundary; "
            "CUDA synchronize and four-rank barrier at each end; includes inter-update logging"
        )
        result["comparison"]["peak_cuda_memory"] = {
            backend: peak_memory(args.output / backend, backend) for backend in ("tp", "fsdp")
        }
        result["comparison"].update(
            provisional=result["provisional"],
            performance_acceptance=False,
            exclusivity_observation="cooperative lock and periodic GPU-user polling",
            monitor_limitations=(
                "restricted mode cannot bind host NVML PIDs to local processes; transient interference remains possible"
                if result["provisional"]
                else "interference between polling snapshots cannot be excluded"
            ),
        )
        (args.output / "comparison.json").write_text(json.dumps(result["comparison"], indent=2) + "\n")
        result["completed"] = True
    except BaseException as error:
        result["failure"] = f"{type(error).__name__}: {error}"
        raise
    finally:
        prior.save(status, result)


if __name__ == "__main__":
    main()
